/**
 * A horizontal run of black pixels: one <rect> instead of sixteen. Keeps the
 * SVG small enough that a screen full of icons costs nothing.
 */
export interface PixelRun {
  x: number;
  y: number;
  width: number;
}

export function runs(map: PixelMap): PixelRun[] {
  const out: PixelRun[] = [];
  map.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x += 1) {
      const on = row[x] === '#';
      if (on && start === -1) start = x;
      if (!on && start !== -1) {
        out.push({ x: start, y, width: x - start });
        start = -1;
      }
    }
  });
  return out;
}
